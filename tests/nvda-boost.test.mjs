import assert from 'node:assert/strict';
import { GUNS } from '../client/js/data/guns.js';
import { getBoostTickerForGun, getNvdaBoostGunIds, getNvdaBoostRotationKey, getTickerBoostGunIds } from '../client/js/data/nvda-boost.js';

const date = new Date('2026-10-21T12:00:00Z');
const nvdaA = getNvdaBoostGunIds(GUNS, date);
const nvdaB = getNvdaBoostGunIds(GUNS, date);
const tsla = getTickerBoostGunIds('TSLA', GUNS, date);
const msft = getTickerBoostGunIds('MSFT', GUNS, date);
assert.equal(nvdaA.length, 3);
assert.deepEqual(nvdaA, nvdaB);
assert.equal(new Set(nvdaA).size, 3);
assert.equal(new Set(nvdaA.map((id) => GUNS.find((gun) => gun.id === id).cls)).size, 3);
assert.deepEqual(tsla, ['mp9', 'xm1014']);
assert.deepEqual(msft, ['p2000', 'm4a1']);
assert.equal(new Set([...nvdaA, ...tsla, ...msft]).size, 7, 'ticker boosts must not overlap');
assert.equal(getBoostTickerForGun('mp9', GUNS, date), 'TSLA');
assert.equal(getBoostTickerForGun('xm1014', GUNS, date), 'TSLA');
assert.equal(getBoostTickerForGun('p2000', GUNS, date), 'MSFT');
assert.equal(getBoostTickerForGun('m4a1', GUNS, date), 'MSFT');
assert.equal(getNvdaBoostRotationKey(date), 'nvda-boost:2026-10-21');
console.log(`ticker boost routing: ALL PASS (NVDA=${nvdaA.join(', ')}; TSLA=${tsla.join(', ')}; MSFT=${msft.join(', ')})`);
